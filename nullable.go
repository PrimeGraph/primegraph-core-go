package primegraphcore

import (
	"encoding/json"
	"time"
)

// The Nullable* wrappers are the carrier a model field marked `nullable: true`
// materialises as. A wrapper distinguishes "absent" from "present and null",
// which a bare pointer cannot, and it is a nominal type a model field of one
// generated package hands to a function of another — so it is declared once
// here rather than once per package.

type NullableBool struct {
	value *bool
	isSet bool
}

func (v NullableBool) Get() *bool {
	return v.value
}

func (v *NullableBool) Set(val *bool) {
	v.value = val
	v.isSet = true
}

func (v NullableBool) IsSet() bool {
	return v.isSet
}

func (v *NullableBool) Unset() {
	v.value = nil
	v.isSet = false
}

func NewNullableBool(val *bool) *NullableBool {
	return &NullableBool{value: val, isSet: true}
}

func (v NullableBool) MarshalJSON() ([]byte, error) {
	return json.Marshal(v.value)
}

func (v *NullableBool) UnmarshalJSON(src []byte) error {
	v.isSet = true
	return json.Unmarshal(src, &v.value)
}

