// The *Of lifts turn a DSL-width scalar into the wrapper's value form, so an
// expression result can flow straight into a nullable model field.

func NullableStringOf(v string) NullableString {
	return *NewNullableString(&v)
}

func NullableInt64Of(v int64) NullableInt64 {
	return *NewNullableInt64(&v)
}

func NullableFloat64Of(v float64) NullableFloat64 {
	return *NewNullableFloat64(&v)
}

func NullableBoolOf(v bool) NullableBool {
	return *NewNullableBool(&v)
}
